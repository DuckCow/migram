-- V7: Create reports and moderation_actions tables for content moderation

-- Reports table: user-submitted reports on posts/comments
CREATE TABLE report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL,
    content_type VARCHAR(20) NOT NULL,  -- POST or COMMENT
    post_id BIGINT,
    comment_id BIGINT,
    reason VARCHAR(50) NOT NULL,  -- SPAM, HARASSMENT, HATE_SPEECH, etc.
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',  -- PENDING, RESOLVED, REJECTED
    reviewed_by BIGINT,
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_report_reporter FOREIGN KEY (reporter_id) REFERENCES users(id),
    CONSTRAINT fk_report_post FOREIGN KEY (post_id) REFERENCES post(id) ON DELETE CASCADE,
    CONSTRAINT fk_report_comment FOREIGN KEY (comment_id) REFERENCES comment(id) ON DELETE CASCADE,
    CONSTRAINT fk_report_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id),

    -- XOR constraint: exactly one of post_id or comment_id must be set
    CONSTRAINT chk_report_target CHECK (
        (post_id IS NOT NULL AND comment_id IS NULL) OR
        (post_id IS NULL AND comment_id IS NOT NULL)
    )
);

-- Indexes for reports
CREATE INDEX idx_report_status ON report(status);
CREATE INDEX idx_report_content_type ON report(content_type);
CREATE INDEX idx_report_post ON report(post_id) WHERE post_id IS NOT NULL;
CREATE INDEX idx_report_comment ON report(comment_id) WHERE comment_id IS NOT NULL;
CREATE INDEX idx_report_created_at ON report(created_at DESC);

-- Moderation actions audit log (append-only, immutable)
CREATE TABLE moderation_action (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_type VARCHAR(20) NOT NULL,  -- POST or COMMENT
    content_id BIGINT NOT NULL,
    report_id BIGINT,  -- nullable: action can be taken without a report
    action_type VARCHAR(30) NOT NULL,  -- NO_ACTION, SET_LIMITED, SET_HIDDEN, SET_REMOVED, RESTORE_PUBLIC
    admin_id BIGINT NOT NULL,
    note TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_moderation_action_admin FOREIGN KEY (admin_id) REFERENCES users(id),
    CONSTRAINT fk_moderation_action_report FOREIGN KEY (report_id) REFERENCES report(id)
);

-- Indexes for moderation actions
CREATE INDEX idx_moderation_action_content ON moderation_action(content_type, content_id);
CREATE INDEX idx_moderation_action_admin ON moderation_action(admin_id);
CREATE INDEX idx_moderation_action_created_at ON moderation_action(created_at DESC);
