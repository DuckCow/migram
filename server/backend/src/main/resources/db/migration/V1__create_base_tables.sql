-- V1: Create base tables
-- All entity DDLs for Fresh DB support
-- Compatible with PostgreSQL and H2 (MODE=PostgreSQL)

-- ============================================
-- 1. users (no FK dependencies)
-- ============================================
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    profile_picture VARCHAR(255),
    nickname VARCHAR(255),
    nickname_key VARCHAR(255),
    origin_country VARCHAR(50),
    current_country VARCHAR(50),
    allow_dms_from VARCHAR(50) DEFAULT 'FOLLOWERS_ONLY',
    CONSTRAINT uq_users_nickname UNIQUE (nickname),
    CONSTRAINT uq_users_nickname_key UNIQUE (nickname_key)
);

-- ============================================
-- 2. user_roles (ElementCollection for User.roles)
-- ============================================
CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL,
    roles VARCHAR(50) NOT NULL,
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_user_roles_user ON user_roles(user_id);

-- ============================================
-- 3. boards (FK to users)
-- ============================================
CREATE TABLE IF NOT EXISTS boards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    board_type VARCHAR(50) NOT NULL DEFAULT 'COUNTRY',
    context VARCHAR(100),
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    board_created_by BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(255),
    modified_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_boards_user FOREIGN KEY (board_created_by) REFERENCES users(id)
);

-- ============================================
-- 4. post (FK to users, boards)
-- ============================================
CREATE TABLE IF NOT EXISTS post (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    media_url VARCHAR(255),
    board_id BIGINT NOT NULL,
    is_anonymous BOOLEAN NOT NULL DEFAULT FALSE,
    original_lang VARCHAR(10) NOT NULL DEFAULT 'en',
    user_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(255),
    modified_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_post_board FOREIGN KEY (board_id) REFERENCES boards(id),
    CONSTRAINT fk_post_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_post_board ON post(board_id);
CREATE INDEX IF NOT EXISTS idx_post_title ON post(title);
CREATE INDEX IF NOT EXISTS idx_post_media_url ON post(media_url);

-- ============================================
-- 5. comment (FK to users, post, self-reference)
-- ============================================
CREATE TABLE IF NOT EXISTS comment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL,
    original_lang VARCHAR(10) NOT NULL DEFAULT 'en',
    post_id BIGINT,
    user_id BIGINT,
    parent_comment_id BIGINT,
    reply_to_username VARCHAR(100),
    reply_to_user_id BIGINT,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(255),
    modified_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comment_post FOREIGN KEY (post_id) REFERENCES post(id),
    CONSTRAINT fk_comment_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_comment_parent FOREIGN KEY (parent_comment_id) REFERENCES comment(id)
);

-- ============================================
-- 6. authorization_codes (no FK)
-- ============================================
CREATE TABLE IF NOT EXISTS authorization_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL,
    email VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_authorization_codes_code UNIQUE (code)
);

-- ============================================
-- 7. blocks (FK to users)
-- ============================================
CREATE TABLE IF NOT EXISTS blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id BIGINT NOT NULL,
    blocked_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_blocks_blocker FOREIGN KEY (blocker_id) REFERENCES users(id),
    CONSTRAINT fk_blocks_blocked FOREIGN KEY (blocked_id) REFERENCES users(id),
    CONSTRAINT uq_blocks_pair UNIQUE (blocker_id, blocked_id)
);
CREATE INDEX IF NOT EXISTS idx_block_blocker ON blocks(blocker_id);
CREATE INDEX IF NOT EXISTS idx_block_blocked ON blocks(blocked_id);

-- ============================================
-- 8. chat_rooms (FK to users)
-- ============================================
CREATE TABLE IF NOT EXISTS chat_rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user1_id BIGINT NOT NULL,
    user2_id BIGINT NOT NULL,
    initiator_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    last_message_at TIMESTAMP,
    last_message_preview VARCHAR(200),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chatroom_user1 FOREIGN KEY (user1_id) REFERENCES users(id),
    CONSTRAINT fk_chatroom_user2 FOREIGN KEY (user2_id) REFERENCES users(id),
    CONSTRAINT fk_chatroom_initiator FOREIGN KEY (initiator_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_chatroom_user1 ON chat_rooms(user1_id);
CREATE INDEX IF NOT EXISTS idx_chatroom_user2 ON chat_rooms(user2_id);
CREATE INDEX IF NOT EXISTS idx_chatroom_updated ON chat_rooms(last_message_at);
CREATE INDEX IF NOT EXISTS idx_chatroom_status ON chat_rooms(status);

-- ============================================
-- 9. follow (FK to users)
-- ============================================
CREATE TABLE IF NOT EXISTS follow (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL,
    target_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'REQUESTED',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at TIMESTAMP,
    CONSTRAINT fk_follow_requester FOREIGN KEY (requester_id) REFERENCES users(id),
    CONSTRAINT fk_follow_target FOREIGN KEY (target_id) REFERENCES users(id),
    CONSTRAINT uq_follow_pair UNIQUE (requester_id, target_id)
);
CREATE INDEX IF NOT EXISTS idx_follow_requester ON follow(requester_id);
CREATE INDEX IF NOT EXISTS idx_follow_target ON follow(target_id);
CREATE INDEX IF NOT EXISTS idx_follow_status ON follow(status);

-- ============================================
-- 10. likes (legacy table, FK to users, post, comment)
-- ============================================
CREATE TABLE IF NOT EXISTS likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    post_id BIGINT,
    comment_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_likes_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_likes_post FOREIGN KEY (post_id) REFERENCES post(id),
    CONSTRAINT fk_likes_comment FOREIGN KEY (comment_id) REFERENCES comment(id)
);

-- ============================================
-- 11. messages (FK to chat_rooms, users)
-- ============================================
CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_room_id BIGINT NOT NULL,
    sender_id BIGINT NOT NULL,
    content VARCHAR(2000),
    image_url VARCHAR(500),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    read_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_message_chatroom FOREIGN KEY (chat_room_id) REFERENCES chat_rooms(id),
    CONSTRAINT fk_message_sender FOREIGN KEY (sender_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_message_chatroom ON messages(chat_room_id);
CREATE INDEX IF NOT EXISTS idx_message_sender ON messages(sender_id);
CREATE INDEX IF NOT EXISTS idx_message_created ON messages(created_at);

-- ============================================
-- 12. notifications (FK to users)
-- ============================================
CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    type VARCHAR(50) NOT NULL,
    reference_id BIGINT,
    message VARCHAR(500) NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notification_recipient FOREIGN KEY (recipient_id) REFERENCES users(id),
    CONSTRAINT fk_notification_actor FOREIGN KEY (actor_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_notification_recipient ON notifications(recipient_id);
CREATE INDEX IF NOT EXISTS idx_notification_created ON notifications(created_at_timestamp);
CREATE INDEX IF NOT EXISTS idx_notification_read ON notifications(is_read);
