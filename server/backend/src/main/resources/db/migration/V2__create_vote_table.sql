-- V2: Create votes table
-- DDL based on Vote.kt entity
-- Compatible with PostgreSQL and H2 (MODE=PostgreSQL)

CREATE TABLE IF NOT EXISTS votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    post_id BIGINT,
    comment_id BIGINT,
    vote_type VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_votes_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_votes_post FOREIGN KEY (post_id) REFERENCES post(id),
    CONSTRAINT fk_votes_comment FOREIGN KEY (comment_id) REFERENCES comment(id),
    CONSTRAINT uq_votes_user_post UNIQUE (user_id, post_id),
    CONSTRAINT uq_votes_user_comment UNIQUE (user_id, comment_id),
    CONSTRAINT chk_votes_post_xor_comment CHECK ((post_id IS NOT NULL) <> (comment_id IS NOT NULL))
);

-- Indexes from Vote.kt @Index annotations
CREATE INDEX IF NOT EXISTS idx_votes_post_type ON votes(post_id, vote_type);
CREATE INDEX IF NOT EXISTS idx_votes_comment_type ON votes(comment_id, vote_type);

-- Additional indexes for query performance
CREATE INDEX IF NOT EXISTS idx_votes_user_post ON votes(user_id, post_id);
CREATE INDEX IF NOT EXISTS idx_votes_user_comment ON votes(user_id, comment_id);
CREATE INDEX IF NOT EXISTS idx_votes_created_at ON votes(created_at);
