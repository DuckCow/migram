-- V5: Add translation support
-- Note: original_lang columns in Post/Comment entities are managed by Hibernate
-- This migration only creates the content_translation cache table

-- Create content_translation table for caching translations
CREATE TABLE IF NOT EXISTS content_translation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_type VARCHAR(20) NOT NULL,
    content_id BIGINT NOT NULL,
    target_lang VARCHAR(10) NOT NULL,
    translated_text TEXT NOT NULL,
    model VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT unique_translation UNIQUE (content_type, content_id, target_lang)
);

-- Create index for faster lookups
CREATE INDEX IF NOT EXISTS idx_content_translation_lookup ON content_translation(content_type, content_id, target_lang);
CREATE INDEX IF NOT EXISTS idx_content_translation_created ON content_translation(created_at);
